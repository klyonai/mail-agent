test('provider retry deadline survives restart and suppresses early polling', async t => {
  let now = 10_000;
  let polls = 0;
  const mail = {
    poll: async () => {
      polls++;
      if (polls === 1) throw Object.assign(new Error('safe throttling failure'), {
        diagnosticCode: 'throttled', retryNotBefore: now + 60_000
      });
      return { messages: [], cursor: JSON.stringify({ initialComplete: true }) };
    }
  };
  const h = await harness(t, { mail, clock: () => now });
  const failed = await h.runtime.start({ once: true });
  assert.equal(polls, 1);
  assert.equal(failed.sync.retryNotBefore, 70_000);
  assert.equal(failed.sync.lastFailure.code, 'throttled');

  const restarted = await h.restart();
  const deferred = await restarted.start({ once: true });
  assert.equal(polls, 1);
  assert.equal(deferred.sync.retryNotBefore, 70_000);

  now = 70_000;
  await restarted.start({ once: true });
  assert.equal(polls, 2);
  assert.equal(restarted.status().sync.retryNotBefore, null);
});

test('Retry-After observed during shutdown cancellation survives restart', async t => {
  let now = 20_000;
  let polls = 0;
  let enterPoll;
  const polling = new Promise(resolve => { enterPoll = resolve; });
  const mail = { poll: async ({ signal }) => {
    polls++;
    if (polls > 1) return { messages: [], cursor: JSON.stringify({ initialComplete: true }) };
    enterPoll();
    return new Promise((_, reject) => {
      signal.addEventListener('abort', () => reject(Object.assign(new Error('cancelled poll'), {
        name: 'AbortError', retryNotBefore: now + 60_000
      })), { once: true });
    });
  } };
  const h = await harness(t, { mail, clock: () => now });
  const started = h.runtime.start();
  await polling;
  await h.runtime.stop();
  await started;
  assert.equal(h.runtime.status().sync.retryNotBefore, 80_000);

  const restarted = await h.restart();
  const deferred = await restarted.start({ once: true });
  assert.equal(polls, 1);
  assert.equal(deferred.sync.retryNotBefore, 80_000);
  now = 80_000;
  await restarted.start({ once: true });
  assert.equal(polls, 2);
});

