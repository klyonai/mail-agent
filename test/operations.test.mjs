async function harness(t, overrides = {}) {
  const root = await mkdtemp(join(tmpdir(), 'mail-agent-operations-'));
  const config = {
    id: 'operations-test', state_root: './state',
    mailbox: { address: 'agent@example.org', tenant_id: 'tenant', client_id: 'client', poll_seconds: 30 },
    model: { capabilities: { tools: false } },
    policy: { senders: ['alice@example.org'], recipients: ['alice@example.org'], approvers: ['admin@example.org'], tools: {} },
    mcp: {}, limits: { model_calls: 6, tool_calls: 10, run_seconds: 120, context_tokens: 16000, output_tokens: 2000, queue_messages: 100 },
    retention: { content_hours: 24, audit_days: 30 }
  };
  if (overrides.mode === 'live') config.mailbox.sender_authentication = { transport_headers_verified: true };
  const loaded = {
    config, root, instructions: 'Answer helpfully.', hash: 'operations-config',
    model: { step: async () => ({ text: 'A useful reply.', toolCalls: [] }) },
    mail: { reply: async () => ({ status: 'accepted' }) },
    listenControl: async () => ({ close: async () => {} }),
    ...overrides
  };
  const runtime = await createRuntime(loaded);
  const runtimes = [runtime];
  t.after(async () => {
    for (const instance of [...runtimes].reverse()) await instance.stop();
    await rm(root, { recursive: true, force: true });
  });
  const restart = async () => {
    await runtimes.at(-1).stop();
    const instance = await createRuntime(loaded);
    runtimes.push(instance);
    return instance;
  };
  return { root, config, loaded, runtime, restart };
}

function message(id, overrides = {}) {
  return {
    id, conversationId: `conversation-${id}`, sender: 'alice@example.org',
    replyTo: 'alice@example.org', to: ['agent@example.org'], cc: [], subject: 'Question',
    body: 'Please explain.', receivedAt: '2026-01-01T00:00:00Z', authenticated: true,
    autoGenerated: false, attachments: false, ...overrides
  };
}

test('status preserves legacy fields and returns bounded, cursor-paginated run metadata', async t => {
  const h = await harness(t);
  for (const id of ['one', 'two', 'three']) assert.equal((await h.runtime.processMessage(message(id))).status, 'completed');

  const first = h.runtime.status({ limit: 1 });
  assert.equal(first.agent, h.config.id);
  assert.equal(first.mailbox, h.config.mailbox.address);
  assert.equal(first.dependencyError, null);
  assert.ok(Array.isArray(first.runs));
  assert.equal(first.runs.length, 1);
  assert.ok(first.nextCursor);
  assert.equal(first.counts.completed, 3);
  assert.equal(first.sync.baseline, 'not-started');

  const second = h.runtime.status({ limit: 1, after: first.nextCursor });
  assert.equal(second.runs.length, 1);
  assert.notEqual(second.runs[0].id, first.runs[0].id);
  assert.ok(second.nextCursor);
  const final = h.runtime.status({ limit: 1, after: second.nextCursor });
  assert.equal(final.runs.length, 1);
  assert.notEqual(final.runs[0].id, second.runs[0].id);
  assert.equal(h.runtime.status({ limit: 1, after: final.nextCursor }).runs.length, 0);
  assert.throws(() => h.runtime.status({ limit: 101 }), /Page limit/);
  assert.throws(() => h.runtime.status({ after: 'not-a-cursor' }), /Invalid metadata cursor/);
});

