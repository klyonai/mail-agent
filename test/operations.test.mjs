  assert.equal(failure.resolvedAt, null);

  now += 10;
  await h.runtime.start({ once: true });
  const stillRecorded = h.runtime.status().failures.model;
  assert.equal(stillRecorded.at, failure.at);
  assert.equal(stillRecorded.resolvedAt, null);

  now += 10;
  await h.runtime.processMessage(message('model-recovered'));
  const recovered = h.runtime.status().failures.model;
  assert.equal(recovered.code, 'model-unsupported');
  assert.equal(recovered.at, failure.at);
  assert.equal(recovered.resolvedAt, now);
