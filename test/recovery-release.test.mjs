  const f=await fixture(t);
  const gap={...f.request,plan:{...f.request.plan,mode:'history-gap',acceptHistoryGap:true}};
  await assert.rejects(previewRecoveryRelease(gap,{graphFactory:()=>({poll:async()=>{throw new Error('PRIVATE_PROVIDER_ERROR');}})}),
    error=>error.code==='RECOVERY_RELEASE_INVALID'&&!error.message.includes('PRIVATE'));
  const controller=new AbortController();controller.abort();
