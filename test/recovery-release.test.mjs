  await assert.rejects(previewRecoveryRelease(gap,{graphFactory:()=>({poll:async()=>({messages:[],
    cursor:cursor.replace('graph.microsoft.com','untrusted.example.test')})})}));
  f.inspect(store=>store.setMeta('sync.retry',String(now+1000)));
