test('one hundred legal Unicode action decisions fit a byte-bounded private receipt and remain idempotent', async t => {
  const f = await fixture(t);
  const decisions = f.inspect(store => Array.from({ length: 100 }, (_, index) => {
    const key = `${index}${'漢'.repeat(250)}`;
    store.saveAction({ key, runId: 'run-one', state: 'uncertain', effect: 'write' });
    return { kind: 'action', key, fingerprint: store.actionFingerprint(key), outcome: 'no-effect', evidence: evidence('adapter') };
  }));
  const plan = makePlan(decisions), input = await reviewed(f, plan);
  await applyRecovery(input);
  const raw = f.inspect(store => store.getMeta(`recovery_batch:${input.expectedPlanDigest}`));
  assert.ok(Buffer.byteLength(raw) > 65_536);
  assert.ok(Buffer.byteLength(raw) <= 262_144);
  assert.equal(JSON.parse(raw).actions.length, 100);
  assert.equal((await applyRecovery(input)).idempotent, true);
});
