const identity = 'a'.repeat(64), configHash = 'b'.repeat(64), agentId = 'synthetic-agent';
const snapshotId = '11111111-1111-4111-8111-111111111111';
const limits = { model_calls: 6, tool_calls: 10, run_seconds: 120 };
const evidence = (source = 'adapter') => ({ source, recordHash: 'c'.repeat(64), observedAt: 30 });
const actor = 'operator@example.test', reason = 'Synthetic provider reconciliation.';
const hold = JSON.stringify({ snapshotId, snapshotCreatedAt: 10, restoredAt: 20 });
const cursor = JSON.stringify({ initialComplete: true, url: 'SYNTHETIC_PRIVATE_CURSOR' });
const binding = digest([identity, hold, cursor]);
const mail = () => ({ id: 'SYNTHETIC_PRIVATE_PROVIDER_ID', conversationId: 'SYNTHETIC_PRIVATE_CONVERSATION', sender: 'sender@example.test',
  to: ['agent@example.test'], cc: [], subject: 'SYNTHETIC_PRIVATE_SUBJECT', body: 'SYNTHETIC_PRIVATE_BODY', authenticated: true, autoGenerated: false });
const run = (id = 'run-one', extra = {}) => ({ id, messageKey: digest([agentId, id]), conversationKey: digest(id), sequence: 1,
  status: 'queued', createdAt: 15, budget: { modelCalls: 2, toolCalls: 1, activeMs: 5 }, mail: mail(),
  grants: { 'synthetic-grant': { actor: 'admin@example.test', expiresAt: 900, policyHash: 'synthetic-policy' } }, ...extra });

async function fixture(t, records = [run()]) {
  const root = await mkdtemp(join(tmpdir(), 'ma-recovery-apply-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const store = openStore(root, { identity, clock: () => 30 });
  store.setMeta('restore_hold', hold);
  store.setMeta('cursor', cursor);
  store.setMeta('queue_sequence', '9');
  for (const value of records) store.saveRun(value);
  store.close();
  const options = { stateRoot: root, identity, agentId, configHash, limits, contentHours: 24, clock: () => 30 };
  return { options, inspect: callback => {
    const current = openStore(root, { identity, clock: () => 30 });
    try { return callback(current); } finally { current.close(); }
  } };
}

function makePlan(operations) { return { format: 1, mailboxIdentity: identity, snapshotId, binding, configHash, operations }; }
function runOp(f, id = 'run-one', outcome = 'resume', source = 'adapter') {
  return { kind: 'run', id, fingerprint: f.inspect(store => store.runFingerprint(id)), outcome, evidence: evidence(source) };
}
function actionOp(f, key, outcome = 'no-effect') {
  return { kind: 'action', key, fingerprint: f.inspect(store => store.actionFingerprint(key)), outcome, evidence: evidence('adapter') };
}
async function reviewed(f, plan, dependencies) {
  const preview = await previewRecovery({ ...f.options, plan }, dependencies);
  return { ...f.options, actor, reason, plan, expectedPlanDigest: preview.planDigest };
}

test('preview is metadata-only and apply preserves budgets/grants with one-time reservation accounting while held', async t => {
  const f = await fixture(t, [run('run-one', { status: 'running', activeOperation: { reservedMs: 40 } })]);
  const before = f.inspect(store => ({ run: store.getRun('run-one'), hold: store.getMeta('restore_hold'), cursor: store.getMeta('cursor') }));
  const plan = makePlan([runOp(f)]);
  const preview = await previewRecovery({ ...f.options, plan });
  assert.equal(preview.planDigest, digest(plan));
  assert.equal(JSON.stringify(preview).includes('SYNTHETIC_PRIVATE'), false);
  assert.deepEqual(f.inspect(store => store.getRun('run-one')), before.run);
  const result = await applyRecovery({ ...f.options, actor, reason, plan, expectedPlanDigest: preview.planDigest });
  assert.equal(result.applied, true);
  const after = f.inspect(store => ({ run: store.getRun('run-one'), hold: store.getMeta('restore_hold'), cursor: store.getMeta('cursor') }));
  assert.equal(after.run.status, 'queued');
  assert.deepEqual(after.run.budget, { modelCalls: 2, toolCalls: 1, activeMs: 45 });
  assert.equal(after.run.activeOperation, undefined);
  assert.deepEqual(after.run.grants, before.run.grants);
  assert.deepEqual(after.run.recovery, { binding, planDigest: preview.planDigest, outcome: 'resume', evidenceHash: evidence().recordHash });
  assert.equal(after.hold, before.hold);
  assert.equal(after.cursor, before.cursor);
  const receipt = JSON.parse(f.inspect(store => store.getMeta(`recovery_batch:${preview.planDigest}`)));
  assert.deepEqual(receipt.runs, [{ id: 'run-one', originalFingerprint: plan.operations[0].fingerprint,
    appliedFingerprint: f.inspect(store => store.runFingerprint('run-one')), outcome: 'resume', evidenceHash: evidence().recordHash }]);
  const fingerprint = f.inspect(store => store.runFingerprint('run-one'));
  const repeat = await applyRecovery({ ...f.options, actor, reason, plan, expectedPlanDigest: preview.planDigest });
  assert.equal(repeat.idempotent, true);
  assert.equal(f.inspect(store => store.runFingerprint('run-one')), fingerprint);
  await assert.rejects(applyRecovery({ ...f.options, actor, reason: 'Different attribution', plan, expectedPlanDigest: preview.planDigest }));
});

