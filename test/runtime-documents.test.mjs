test('expired known-run crash partial is collected while unknown run directories remain untouched',async t=>{
  const h=await harness(t);
  await h.runtime.processMessage(message());
  const run=savedRun(h.root),known=join(h.root,'state','artifacts',run.id,randomUUID());
  await mkdir(known,{mode:0o700});await writeFile(join(known,'bytes'),'crash partial',{mode:0o600});
  const unknown=join(h.root,'state','artifacts',randomUUID(),randomUUID());
  await mkdir(unknown,{recursive:true,mode:0o700});await writeFile(join(unknown,'bytes'),'unknown',{mode:0o600});
  h.advance();await h.runtime.processMessage(message());
  await assert.rejects(stat(known),{code:'ENOENT'});
  assert.equal(await readFile(join(unknown,'bytes'),'utf8'),'unknown');
});

test('unsafe orphan content is retained and reports a sanitized operational failure',async t=>{
  const h=await harness(t);await h.runtime.processMessage(message());
  const run=savedRun(h.root),known=join(h.root,'state','artifacts',run.id,randomUUID());
  await mkdir(known,{mode:0o700});await writeFile(join(known,'private-extra'),'keep',{mode:0o600});
  h.advance();await h.runtime.processMessage(message());
  assert.equal(await readFile(join(known,'private-extra'),'utf8'),'keep');
  const failure=h.runtime.status().failures.artifacts;
  assert.equal(failure.code,'dependency-failed');assert.equal(failure.resolvedAt,null);
  assert.doesNotMatch(JSON.stringify(h.runtime.status()),/private-extra|crash partial/);
});
