test('definite prewrite failure resumes exact saved artifact and MIME intent without model or download replay',async t=>{
  const h=await harness(t),payloads=[];
  h.mail.reply=async(source,body,options)=>{
    payloads.push(buildTextAttachmentReply({message:source,bodyText:body,artifact:options.attachment,now:1000}));
    if(payloads.length===1)throw Object.assign(new Error('definite failure'),{uncertain:false});
    return {status:'accepted'};
  };
  assert.equal((await h.runtime.processMessage(message())).status,'ready_to_send');
  const original=savedRun(h.root),resumed=await h.restart();
  assert.equal((await resumed.processMessage(message())).status,'completed');
  assert.equal(h.calls.length,1);assert.equal(h.reads.length,1);
  assert.deepEqual(payloads[0],payloads[1]);assert.deepEqual(savedRun(h.root).deliveryIntent,original.deliveryIntent);
});

