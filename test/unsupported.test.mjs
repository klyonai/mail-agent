test('shutdown during metadata retains queued work and checks again after restart', async t => {
  let enter;
  const entered = new Promise(done => { enter = done; });
  const h = await harness(t, { mail: { getAttachmentMetadata: async () => { enter(); return new Promise(() => {}); } } });
  const pending = h.runtime.processMessage(message({ attachments: false, attachmentStatus: 'unknown' }));
  await entered;
  await h.runtime.stop();
  assert.equal((await pending).status, 'queued'); assert.equal(h.sent.length, 0);
  h.settings.mail.getAttachmentMetadata = async () => ({ kind: 'inline-artifact', count: 1 });
  const restarted = await h.restart();
  assert.equal((await restarted.processMessage(message())).status, 'completed');
  assert.equal(h.sent.length, 1); assert.equal(h.calls.length, 0);
});

test('reloaded recipient revocation blocks the unsupported outbox', async t => {
  const h = await harness(t);
  await h.runtime.stop();
  const cfg = parse(await readFile(new URL('../examples/text-inbox/agent.yaml', import.meta.url), 'utf8'));
  cfg.state_root = './reload-state'; cfg.mailbox.address = 'agent@example.org';
  cfg.policy.senders = ['alice@example.org']; cfg.policy.recipients = ['alice@example.org'];
  const filename = join(h.settings.root, 'agent.yaml');
  await writeFile(join(h.settings.root, 'AGENT.md'), 'Text only.');
  await writeFile(filename, stringify(cfg));
  const loaded = await loadConfig(filename);
  const mail = { ...h.settings.mail, getAttachmentMetadata: async () => {
    cfg.policy.recipients = ['bob@example.org']; await writeFile(filename, stringify(cfg));
    return { kind: 'inline-artifact', count: 1 };
  } };
  const runtime = await createRuntime({ ...loaded, mail, model: h.settings.model, mcp: h.settings.mcp });
  try {
    assert.equal((await runtime.processMessage(message({ attachments: false, attachmentStatus: 'unknown' }))).status, 'failed');
    assert.equal(h.sent.length, 0); assert.equal(h.calls.length, 0);
  } finally { await runtime.stop(); }
});

test('recovery of a classified unsupported run cannot fall through to inference', async t => {
  let sends = 0;
  const h = await harness(t, { mail: { reply: async () => {
    sends++; if (sends === 1) throw Object.assign(new Error('definitely rejected'), { uncertain: false });
    return { status: 'accepted' };
  } } });
  const first = await h.runtime.processMessage(message());
  assert.equal(first.status, 'ready_to_send');
  await h.runtime.stop();
  const identity = digest([h.config.id, h.config.mailbox.tenant_id, h.config.mailbox.client_id, h.config.mailbox.address]);
  const store = openStore(join(h.settings.root, 'state'), { identity });
  const run = store.getRun(first.runId);
  run.status = 'running'; delete run.reply;
  store.saveRun(run); store.close();
  const restarted = await h.restart();
  assert.equal((await restarted.processMessage(message())).status, 'completed');
  assert.equal(h.calls.length, 0); assert.equal(h.discoveries.length, 0); assert.equal(sends, 2);
});
