test('unsupported outbox uses existing uncertainty fence without automatic replay', async t => {
  let attempts = 0;
  const h = await harness(t, { mail: { reply: async () => { attempts++; throw Object.assign(new Error('private'), { uncertain: true }); } } });
  assert.equal((await h.runtime.processMessage(message())).status, 'uncertain');
  const restarted = await h.restart();
  assert.equal((await restarted.processMessage(message())).status, 'uncertain');
  assert.equal(attempts, 1); assert.equal(h.calls.length, 0);
});

