test('initial mailbox baseline never probes old attachment metadata or replies', async t => {
  let probes = 0, page = 0;
  const h = await harness(t, { mail: {
    getAttachmentMetadata: async () => { probes++; return { kind: 'inline-artifact', count: 1 }; },
    poll: async () => ({ messages: [message({ id: `page-${++page}`, attachments: false, attachmentStatus: 'unknown' })],
      cursor: JSON.stringify({ url: 'synthetic', initialComplete: page >= 2 }) })
  } });
  await h.runtime.start({ once: true });
  await h.runtime.start({ once: true });
  assert.equal(probes, 0); assert.equal(h.sent.length, 0);
  await h.runtime.start({ once: true });
  assert.equal(probes, 1); assert.equal(h.sent.length, 1); assert.equal(h.calls.length, 0);
});

