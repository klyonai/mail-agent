function message(overrides = {}) {
  return { id: 'unsupported-1', conversationId: 'thread-1', sender: 'alice@example.org',
    replyTo: 'alice@example.org', to: ['agent@example.org'], cc: [], subject: 'Private subject',
    body: 'Private request', authenticated: true, autoGenerated: false, attachments: true,
    receivedAt: '2026-01-01T00:00:00Z', ...overrides };
}

async function harness(t, options = {}) {
  const root = await mkdtemp(join(tmpdir(), 'ma-unsupported-'));
  const config = { id: 'unsupported', state_root: './state',
    mailbox: { address: 'agent@example.org', tenant_id: 'tenant', client_id: 'client' },
    model: { capabilities: { tools: false } }, mcp: {},
    policy: { senders: ['alice@example.org'], recipients: ['alice@example.org'], approvers: [], tools: {} },
    limits: { model_calls: 6, tool_calls: 10, run_seconds: 120, context_tokens: 16000,
      output_tokens: 2000, queue_messages: 100 }, retention: { content_hours: 24, audit_days: 30 } };
  const sent = [], calls = [], discoveries = [];
  const mail = { reply: async (mail, text) => { sent.push({ mail, text }); return { status: 'accepted' }; }, ...options.mail };
  const settings = { config, root, instructions: 'Help with text requests.', hash: 'synthetic', mail,
    model: { step: async input => { calls.push(input); return { text: 'Text answer', toolCalls: [] }; } },
    mcp: { listTools: async () => { discoveries.push(true); return new Map(); }, close: async () => {} } };
  const runtimes = [await createRuntime(settings)];
  t.after(async () => { for (const runtime of runtimes.reverse()) await runtime.stop(); await rm(root, { recursive: true, force: true }); });
  return { runtime: runtimes[0], config, settings, sent, calls, discoveries, restart: async () => {
    await runtimes.at(-1).stop(); const runtime = await createRuntime(settings); runtimes.push(runtime); return runtime;
  } };
}

test('authorized attachment request gets one deterministic explanation across replay and restart', async t => {
  const h = await harness(t);
  assert.equal((await h.runtime.processMessage(message())).status, 'completed');
  assert.equal(h.calls.length, 0);
  assert.equal(h.discoveries.length, 0);
  assert.equal(h.sent.length, 1);
  assert.match(h.sent[0].text, /plain text|attachments/i);
  assert.ok(h.sent[0].text.length < 512);
  assert.doesNotMatch(h.sent[0].text, /Private subject|Private request/);
  const restarted = await h.restart();
  assert.equal((await restarted.processMessage(message())).status, 'completed');
  assert.equal(h.sent.length, 1);
});

test('unsupported unauthorized, automatic, redirected, CC-only and self mail stays silent', async t => {
  let metadata = 0;
  const h = await harness(t, { mail: { getAttachmentMetadata: async () => { metadata++; return { kind: 'document' }; } } });
  const denied = [{ sender: 'outsider@example.org' }, { authenticated: false }, { authenticated: 'yes' },
    { autoGenerated: true }, { to: [], cc: ['agent@example.org'] }, { replyTo: 'outsider@example.org' }];
  for (const [index, override] of denied.entries()) {
    assert.equal((await h.runtime.processMessage(message({ id: `denied-${index}`, attachments: false, attachmentStatus: 'unknown', ...override }))).status, 'ignored');
  }
  h.config.policy.senders.push('agent@example.org'); h.config.policy.recipients.push('agent@example.org');
  assert.equal((await h.runtime.processMessage(message({ id: 'self', attachments: false, sender: 'agent@example.org', replyTo: 'agent@example.org' }))).status, 'ignored');
  h.config.policy.recipients = [];
  assert.equal((await h.runtime.processMessage(message({ id: 'no-recipient', attachments: false, attachmentStatus: 'unknown' }))).status, 'ignored');
  assert.equal(metadata, 0); assert.equal(h.calls.length, 0); assert.equal(h.sent.length, 0);
});

test('inline and unknown metadata fail closed without inference or attachment contents', async t => {
  for (const kind of ['inline-artifact', 'document', 'unknown']) {
    let metadata = 0;
    const h = await harness(t, { mail: { getAttachmentMetadata: async (id, { signal }) => {
      metadata++; assert.equal(id, 'unsupported-1'); assert.ok(signal); return { kind, count: 1 };
    } } });
    assert.equal((await h.runtime.processMessage(message({ attachments: false, attachmentStatus: 'unknown' }))).status, 'completed');
    assert.equal(metadata, 1); assert.equal(h.calls.length, 0); assert.equal(h.sent.length, 1);
    assert.equal(h.discoveries.length, 0);
  }
});

