test('indexed metadata pages are bounded, ordered and cancellable without scanning terminal history', async t => {
  const f = await fixture(t, 101); await f.reconcile();
  let pages = 0, reads = 0, checks = 0;
  const result = f.inspect(store => {
    store.listRuns = () => { throw new Error('Forbidden history scan'); };
    store.actions = () => { throw new Error('Forbidden action scan'); };
    store.activeBatch = () => { throw new Error('Forbidden full-row page'); };
    store.getMeta = () => { throw new Error('Forbidden unbounded metadata read'); };
    const page = store.activeRecoveryPage, getRun = store.getRun;
    store.activeRecoveryPage = options => { pages++; assert.equal(options.limit, 100); return page(options); };
    store.getRun = id => { reads++; return getRun(id); };
    return verifyRecoveryLedger(store, { ...context, checkCancelled: () => { checks++; } });
  });
  assert.equal(result.count, 101); assert.equal(pages, 2); assert.equal(reads, 101); assert.ok(checks >= 103);
  assert.throws(() => f.inspect(store => verifyRecoveryLedger(store, { ...context, maxRuns: 100 })));
  assert.throws(() => f.inspect(store => verifyRecoveryLedger(store, { ...context, checkCancelled: () => { throw new Error('PRIVATE_CANCEL'); } })),
    error => error.code === 'RECOVERY_LEDGER_INVALID' && !error.message.includes('PRIVATE'));
});

