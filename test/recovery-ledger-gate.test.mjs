test('waiting approvals must be current and identify the exact original pending tool call', async t => {
  const mutations = [
    run => { delete run.approval; }, run => { run.approval = null; }, run => { run.approval.expiresAt = 30; },
    run => { run.approval.expiresAt = '1000'; }, run => { run.approval.policyHash = 'f'.repeat(64); },
    run => { run.approval.tool = 'unknown.tool'; }, run => { run.approval.id = 'f'.repeat(64); },
    run => { run.approval.args = { value: 'different' }; }, run => { run.pending = []; },
    run => { run.pending[0].name = 'unknown.tool'; }, run => { run.pending[0].args = { value: 'different' }; }
  ];
  for (const mutation of mutations) {
    const f = await fixture(t);
    f.inspect(store => { const run = store.getRun('run-0'); waitingApproval(run); mutation(run); store.saveRun(run); });
    await f.reconcile();
    const before = f.inspect(store => store.runFingerprint('run-0'));
    assert.throws(() => f.inspect(store => verifyRecoveryLedger(store, context)));
    assert.equal(f.inspect(store => store.runFingerprint('run-0')), before);
  }
  const f = await fixture(t);
  f.inspect(store => { const run = store.getRun('run-0'); waitingApproval(run); store.saveRun(run); });
  await f.reconcile();
  const disabled = { ...config, model: { capabilities: { tools: false } } };
  assert.throws(() => f.inspect(store => verifyRecoveryLedger(store, { ...context, config: disabled })));
});

